    ;WITH Herencia AS (
        SELECT PERFIL_ID AS ROL_ID
        FROM USUARIO_PERFIL
        WHERE USUARIO_ID = @usuario_id

        UNION ALL

        SELECT np.PADRE_ID
        FROM NODO_PERMISO np
