    @pass     VARCHAR(64),
    @rol      VARCHAR(20),
    @nombre   VARCHAR(50) = NULL,
    @apellido VARCHAR(50) = NULL
AS
BEGIN
    IF EXISTS (SELECT 1 FROM USUARIO WHERE USUARIO = @usuario)
